import { Link } from "react-router-dom";
import { useStudioCtx } from "./StudioLayout";
import { CONSENT_VERSION, formatBYPhone, normalizeBYPhone } from "../../shared/by";

/**
 * Политика обработки персональных данных студии (Закон РБ от 07.05.2021 № 99-З).
 * Текст собирается из настроек студии (config.legal). Это шаблон: перед запуском
 * его стоит показать юристу.
 */
export function PrivacyPage() {
  const { studio } = useStudioCtx();
  const t = { slug: studio.tenant.slug, config: { ...studio.tenant.profile } };
  const c = t.config;
  const l = c.legal;
  const phone = formatBYPhone(normalizeBYPhone(c.phone) ?? c.phone);

  return (
    <main className="wrap pad-top">
      <div className="page-h">
        <Link className="link" to={`/s/${t.slug}/`}>← На сайт</Link>
        <span className="eyebrow">{c.name}</span>
        <h2 style={{ fontSize: "clamp(24px,6vw,34px)" }}>Политика обработки персональных данных</h2>
        <p className="muted">Редакция {CONSENT_VERSION}</p>
      </div>
      {!l ? (
        <div className="notice warn">
          Студия ещё не указала данные оператора персональных данных. Пока это образец страницы.
        </div>
      ) : null}
      <article className="legal">
        <h3>1. Кто обрабатывает данные</h3>
        <p>
          Оператор: {l?.operator ?? "—"}, УНП {l?.unp ?? "—"}, адрес: {l?.legalAddress ?? "—"}. Вопросы о персональных данных:{" "}
          {l?.email ?? "—"}, телефон {phone}.
        </p>

        <h3>2. Какие данные и зачем</h3>
        <ul>
          <li>Имя, номер телефона, марка и модель автомобиля — чтобы записать вас, подтвердить запись и связаться по ней.</li>
          <li>Дата, время и стоимость услуги, отметки об оплате — для выполнения работ и учёта.</li>
          <li>Если вы включите напоминание, — техническая подписка браузера на уведомления, только для одного напоминания за сутки.</li>
        </ul>
        <p>Мы не используем данные для рекламных рассылок и не передаём их третьим лицам для их собственных целей.</p>

        <h3>3. Основание</h3>
        <p>
          Ваше согласие, которое вы даёте отметкой в форме записи, а также необходимость выполнить договор об оказании услуги
          (Закон Республики Беларусь от 7 мая 2021 г. № 99-З «О защите персональных данных»).
        </p>

        <h3>4. Сколько храним</h3>
        <p>
          {l?.retentionDays ?? 365} дней после даты записи. Затем имя, телефон и данные автомобиля автоматически удаляются
          (обезличиваются); остаются только дата, услуга и сумма для бухгалтерского учёта.
        </p>

        <h3>5. Где хранятся данные</h3>
        <p>
          В защищённой базе данных: {l?.dataLocation ?? "Германия (ЕС)"}. Германия входит в перечень иностранных государств,
          обеспечивающих надлежащий уровень защиты прав субъектов персональных данных. Доступ к вашим данным есть только у студии.
        </p>

        <h3>6. Ваши права</h3>
        <ul>
          <li>в любой момент отозвать согласие;</li>
          <li>получить информацию об обработке ваших данных и о том, кому они передавались;</li>
          <li>потребовать исправить данные, прекратить обработку или удалить их;</li>
          <li>обжаловать действия оператора в Национальный центр защиты персональных данных.</li>
        </ul>
        <p>
          Для этого напишите на {l?.email ?? "почту студии"} или обратитесь в студию лично. Отзыв согласия не отменяет уже
          оказанные услуги, но новую запись онлайн без согласия оформить нельзя — можно записаться по телефону.
        </p>
      </article>
    </main>
  );
}
